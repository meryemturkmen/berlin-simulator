import { z } from "zod";

const hex = z.string().regex(/^#[0-9a-fA-F]{6}$/);
export const localizedSchema = z.object({ de: z.string().min(1), en: z.string().min(1) });
export type Localized = z.infer<typeof localizedSchema>;

const point = { x: z.number(), z: z.number() };

export const paletteSchema = z.object({
  /** Default ground where nothing else is mapped (paving in the city). */
  ground: hex,
  grass: z.array(hex).min(1),
  path: hex,
  plaza: hex,
  road: hex,
  curb: hex,
  water: hex,
  walls: z.array(hex).min(1),
  roofs: z.array(hex).min(1),
  foliage: z.array(hex).min(1),
  trunk: hex,
});

export const experienceSchema = z.object({
  id: z.string().regex(/^[a-z0-9_]+$/),
  icon: z.string().min(1).max(8),
  title: localizedSchema,
  description: localizedSchema,
});
export type Experience = z.infer<typeof experienceSchema>;

export const propSchema = z.object({
  type: z.enum(["blanket", "cafe_table", "parasol", "planter", "sign", "market_stall", "bench"]),
  ...point,
  rotation: z.number().default(0),
  color: hex.optional(),
  text: z.string().max(40).optional(),
});
export type PlaceProp = z.infer<typeof propSchema>;

export const seatSchema = z.object({
  id: z.string(),
  ...point,
  heading: z.number(),
  mode: z.enum(["bench", "ground"]),
});

export const npcSpotSchema = z.object({
  npc: z.string(),
  ...point,
  heading: z.number(),
  pose: z.enum(["stand", "sit_ground", "sit_bench", "play_guitar"]).default("stand"),
  companion: z.enum(["dog"]).optional(),
});
export type NpcSpot = z.infer<typeof npcSpotSchema>;

export const shopSchema = z.object({
  /** Invented shop name painted above the shop front. Never a real brand. */
  name: z.string().min(1).max(28),
  ...point,
  /** Direction the sign faces, radians around Y. */
  heading: z.number(),
  color: hex,
  awning: z.boolean().default(true),
});

export const placeSchema = z.object({
  id: z.string().regex(/^[a-z]+$/),
  name: localizedSchema,
  district: localizedSchema,
  tagline: localizedSchema,
  center: z.object({ lat: z.number(), lon: z.number() }),
  /** Half the edge length of the walkable square, in meters. */
  halfSize: z.number().min(40).max(200),
  /** Extra ring of scenery rendered beyond the walkable square. */
  backdrop: z.number().min(0).max(150),
  palette: paletteSchema,
  /** Analytic terrain: smooth bumps (positive) or bowls (negative) on flat ground. */
  terrain: z
    .array(z.object({ ...point, radius: z.number().positive(), height: z.number() }))
    .default([]),
  /** Target number of procedurally scattered trees in green areas without mapped trees. */
  scatterTrees: z.number().min(0).default(0),
  spawn: z.object({ ...point, heading: z.number() }),
  facts: z.array(localizedSchema).min(1),
  props: z.array(propSchema).default([]),
  seats: z.array(seatSchema).default([]),
  shops: z.array(shopSchema).default([]),
  npcs: z.array(npcSpotSchema).default([]),
  experiences: z.array(experienceSchema).min(3).max(5),
  ambient: z.enum(["park", "cafe", "boulevard"]),
  /** Hour of day (0 to 24) when the player first arrives. */
  startHour: z.number().min(0).max(24).default(15),
});

export type Place = z.infer<typeof placeSchema>;
export type PlaceInput = z.input<typeof placeSchema>;
export type Palette = z.infer<typeof paletteSchema>;

/** Scene data generated by the asset pipeline next to each GLB. */
export const manifestSchema = z.object({
  id: z.string(),
  halfSize: z.number(),
  extent: z.number(),
  trees: z.array(z.tuple([z.number(), z.number(), z.number(), z.number()])),
  benches: z.array(z.tuple([z.number(), z.number(), z.number()])),
  lamps: z.array(z.tuple([z.number(), z.number()])),
  stats: z.object({
    buildings: z.number(),
    triangles: z.number(),
    glbBytes: z.number(),
    buildingSource: z.enum(["lod2", "osm"]),
  }),
});
export type PlaceManifest = z.infer<typeof manifestSchema>;
